"""Two-layer resource evidence (SODA Task 008).

The canonical A/B/C classification answers one question:

> Can this surface be generated/recognized from the canonical dictionary +
> deterministic morphology?   (canonical coverage)

This module adds a second, clearly separated evidence layer:

> Is this surface directly attested in the audited Interslavic resource
> ecosystem?   (broader resource-supported coverage)

Design rules (from `docs/RESOURCE_POLICY.md`, Task 007 — treated as the
specification):

- A/B/C semantics are untouched; an alternative-resource hit never promotes a
  token into A or B and is never canonical.
- Only an **exact surface attestation** (normalized primary key) in the
  audited alternative resources counts toward the broader tier. Diacritic
  stripping, etymological folding, historical presence and Hunspell tags are
  recorded as provenance but are NOT independent proof (they do not count).
- A token supported by several resources is counted once (no double counting).
- Every non-canonical evidence result retains provenance: layer + source +
  kind (+ small detail). No large resource payloads are duplicated.

Evidence layers (the terminology of `RESOURCE_POLICY.md` §4):

    canonical                headword/addition in `basic.json` (bucket A)
    canonical_inflection     lexicon paradigm form (A) or morphological
                             fallback (B), generated by `@interslavic/morphology`
    alternative_attestation  exact surface in `isv.dic` / `interslavicfreq`
    orthographic_variant     folded/diacritic-stripped near-miss (candidate,
                             never a match)
    historical_evidence      `slovnik` snapshot hit (same lineage, no weight)
    unresolved               no evidence in any audited layer
    non_lexical              punctuation / numbers (excluded from coverage)
"""

from __future__ import annotations

import gzip
import hashlib
import json
import pickle
import unicodedata
from pathlib import Path

from .normalize import fold_etymological, normalize_word

CANONICAL = "canonical"
CANONICAL_INFLECTION = "canonical_inflection"
ALTERNATIVE_ATTESTATION = "alternative_attestation"
ORTHOGRAPHIC_VARIANT = "orthographic_variant"
HISTORICAL_EVIDENCE = "historical_evidence"
UNRESOLVED = "unresolved"
NON_LEXICAL = "non_lexical"

# Resource identifiers used by the project (SOURCES.md / RESOURCE_POLICY.md).
SRC_BASIC_JSON = "basic.json"
SRC_MORPHOLOGY = "@interslavic/morphology"
SRC_HUNSPELL = "isv.dic"
SRC_FREQ_ISV = "interslavicfreq.small_isv"
SRC_FREQ_ISVX = "interslavicfreq.small_isvx"
SRC_SLOVNIK = "slovnik"

DEFAULT_DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "dictionary"


def _sha256(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def strip_diacritics(word: str) -> str:
    """NFD-decompose and drop combining marks (a documented, conservative
    orthographic-variant key, never an exact match)."""
    decomposed = unicodedata.normalize("NFD", word)
    return "".join(ch for ch in decomposed if unicodedata.category(ch) != "Mn")


class ResourceEvidenceProvider:
    """Lookups over the audited alternative/historical resources.

    In-memory normalized indexes (surfaces are a few hundred thousand entries
    each; a plain dict keeps the implementation small and deterministic).
    ``evidence_for`` never judges linguistic correctness: it returns evidence
    records with provenance, and callers decide what counts.
    """

    def __init__(
        self,
        hunspell_forms: dict[str, str] | None = None,
        freq_isv: dict[str, int] | None = None,
        freq_isvx: dict[str, int] | None = None,
        slovnik_index: dict[str, list[dict]] | None = None,
        provenance: dict | None = None,
    ):
        self.hunspell_forms = hunspell_forms or {}
        self.freq_isv = freq_isv or {}
        self.freq_isvx = freq_isvx or {}
        self.slovnik_index = slovnik_index or {}
        self.provenance = provenance or {}

    @property
    def available(self) -> bool:
        return bool(self.hunspell_forms or self.freq_isv or self.freq_isvx
                    or self.slovnik_index)

    def evidence_for(self, norm: str) -> list[dict]:
        """Evidence records for a non-canonical surface form (bucket C).

        Exact-surface attestation comes first; orthographic-variant near-misses
        are recorded only when there is no exact attestation, so the report can
        answer "why was this token counted / not counted". ``norm`` is the
        token's primary normalized key; only Latin-script surfaces can match
        (the alternative resources are Latin-wordform inventories).
        """
        recs: list[dict] = []

        tags = self.hunspell_forms.get(norm)
        if tags is not None:
            recs.append({
                "layer": ALTERNATIVE_ATTESTATION,
                "source": SRC_HUNSPELL,
                "kind": "exact_surface_attestation",
                "detail": {"tags": tags},
            })
        cb = self.freq_isv.get(norm)
        if cb is not None:
            recs.append({
                "layer": ALTERNATIVE_ATTESTATION,
                "source": SRC_FREQ_ISV,
                "kind": "exact_surface_attestation",
                "detail": {"cB": cb},
            })
        cb = self.freq_isvx.get(norm)
        if cb is not None:
            recs.append({
                "layer": ALTERNATIVE_ATTESTATION,
                "source": SRC_FREQ_ISVX,
                "kind": "exact_surface_attestation",
                "detail": {"cB": cb},
            })
        rows = self.slovnik_index.get(norm)
        if rows:
            recs.append({
                "layer": HISTORICAL_EVIDENCE,
                "source": SRC_SLOVNIK,
                "kind": "headword_or_addition",
                "detail": {"isv": rows[0].get("isv"),
                           "pos": rows[0].get("partOfSpeech")},
            })

        if not any(r["layer"] == ALTERNATIVE_ATTESTATION for r in recs):
            recs.extend(self._orthographic_variants(norm))
        return recs

    def _orthographic_variants(self, norm: str) -> list[dict]:
        """Folded / diacritic-stripped near-misses (candidates, not matches)."""
        folded = fold_etymological(norm)
        stripped = strip_diacritics(norm)
        recs: list[dict] = []
        for variant, kind in ((folded, "folded_etymological"),
                              (stripped, "diacritic_stripped")):
            if variant == norm:
                continue
            hits: list[tuple[str, dict]] = []
            if variant in self.hunspell_forms:
                hits.append((SRC_HUNSPELL, {"tags": self.hunspell_forms[variant]}))
            if variant in self.freq_isv:
                hits.append((SRC_FREQ_ISV, {"cB": self.freq_isv[variant]}))
            if variant in self.freq_isvx:
                hits.append((SRC_FREQ_ISVX, {"cB": self.freq_isvx[variant]}))
            for source, detail in hits:
                recs.append({
                    "layer": ORTHOGRAPHIC_VARIANT,
                    "source": source,
                    "kind": kind,
                    "detail": {"variant": variant, **detail},
                })
        return recs


def attach_evidence(tokens: list, provider: ResourceEvidenceProvider | None = None) -> list:
    """Fill the two-layer evidence fields on every token, in place.

    - A/B tokens are canonical by definition and count toward the broader
      tier (canonical support is the strongest evidence).
    - C tokens get their evidence from ``provider``; only
      ``alternative_attestation`` makes them count toward the broader tier.
    - Non-lexical tokens are excluded from all coverage.

    Call this after ``classify()``. Without a provider the broader tier equals
    the canonical tier (conservative default).
    """
    for token in tokens:
        if not token.is_lexical:
            token.resource_evidence_status = NON_LEXICAL
            token.resource_evidence = []
            token.broader_supported = False
            continue

        cls = token.classification
        if cls == "A":
            matches = token.matches or []
            lemmas = sorted({m.get("lemma") for m in matches if m.get("lemma")})
            headword = any(m.get("entry_type") == "headword" for m in matches)
            status = CANONICAL if headword else CANONICAL_INFLECTION
            token.resource_evidence_status = status
            token.resource_evidence = [{
                "layer": status,
                "source": SRC_BASIC_JSON if headword else SRC_MORPHOLOGY,
                "kind": ("headword_or_addition" if headword
                         else "lexicon_paradigm_form"),
                "detail": {"lemmas": lemmas},
            }]
            token.broader_supported = True
        elif cls == "B":
            matches = token.matches or []
            lemmas = sorted({m.get("lemma") for m in matches if m.get("lemma")})
            token.resource_evidence_status = CANONICAL_INFLECTION
            token.resource_evidence = [{
                "layer": CANONICAL_INFLECTION,
                "source": SRC_MORPHOLOGY,
                "kind": "morphological_fallback",
                "detail": {"lemmas": lemmas},
            }]
            token.broader_supported = True
        elif cls == "C":
            recs = provider.evidence_for(token.normalized) if provider else []
            layers = {r["layer"] for r in recs}
            if ALTERNATIVE_ATTESTATION in layers:
                status = ALTERNATIVE_ATTESTATION
            elif ORTHOGRAPHIC_VARIANT in layers:
                status = ORTHOGRAPHIC_VARIANT
            elif HISTORICAL_EVIDENCE in layers:
                status = HISTORICAL_EVIDENCE
            else:
                status = UNRESOLVED
                recs = []
            token.resource_evidence_status = status
            token.resource_evidence = recs
            token.broader_supported = status == ALTERNATIVE_ATTESTATION
        else:  # pragma: no cover - defensive; classifier never emits other classes
            token.resource_evidence_status = UNRESOLVED
            token.resource_evidence = []
            token.broader_supported = False
    return tokens


def load_default_provider(data_dir: Path | None = None) -> ResourceEvidenceProvider | None:
    """Load whatever audited alternative resources exist under
    ``data/dictionary/audit/`` (gitignored local artifacts).

    Returns None when no resource is present — the evaluator then reports the
    canonical tier only. Every loaded resource is recorded in ``provenance``.
    """
    data_dir = Path(data_dir) if data_dir else DEFAULT_DATA_DIR
    audit = data_dir / "audit"
    if not audit.is_dir():
        return None

    provenance: dict[str, dict] = {}
    hunspell_forms: dict[str, str] = {}
    hunspell_cache = audit / "hunspell" / "_isv_forms.pkl.gz"
    if hunspell_cache.is_file():
        with gzip.open(hunspell_cache, "rb") as fh:
            raw_forms, _stems = pickle.load(fh)
        hunspell_forms = {normalize_word(k): v for k, v in raw_forms.items()}
        provenance[SRC_HUNSPELL] = {
            "path": str(hunspell_cache.relative_to(data_dir)),
            "note": "normalized surface -> raw pipeline tags; cache of "
                    "data/dictionary/audit/hunspell/isv.dic (pinned b84535b)",
            "distinct_surfaces": len(hunspell_forms),
        }

    freq_isv: dict[str, int] = {}
    freq_isvx: dict[str, int] = {}
    try:
        import msgpack
    except ImportError:
        msgpack = None
    for name, target in (("small_isv.msgpack.gz", freq_isv),
                         ("small_isvx.msgpack.gz", freq_isvx)):
        path = audit / "frequency" / name
        if not path.is_file() or msgpack is None:
            continue
        with gzip.open(path, "rb") as fh:
            buckets = msgpack.unpackb(fh.read(), raw=False)[1:]
        for cB, words in enumerate(buckets):
            for w in words:
                target[normalize_word(w)] = -cB
        provenance["interslavicfreq." + name.removesuffix(".msgpack.gz")] = {
            "path": str(path.relative_to(data_dir)),
            "entries": len(target),
            "sha256": _sha256(path),
            "note": "surface -> cB (log-scale frequency); frozen wordlist "
                    "(pinned b84535b); surface attestation only",
        }

    slovnik_index: dict[str, list[dict]] = {}
    slovnik_path = audit / "slovnik" / "basic.json"
    if slovnik_path.is_file():
        with open(slovnik_path, encoding="utf-8") as fh:
            data = json.load(fh)
        wordlist = data["wordList"]
        header = [str(h) for h in wordlist[0]]
        for row in wordlist[1:]:
            record = dict(zip(header, row))
            keys = [record.get("isv", "")]
            addition = str(record.get("addition") or "")
            keys += [a.strip() for a in addition.split(",") if a.strip()]
            for k in keys:
                norm = normalize_word(k)
                if not norm:
                    continue
                slovnik_index.setdefault(norm, []).append(record)
        provenance[SRC_SLOVNIK] = {
            "path": str(slovnik_path.relative_to(data_dir)),
            "headword_or_addition_keys": len(slovnik_index),
            "sha256": _sha256(slovnik_path),
            "note": "historical snapshot, same lineage as basic.json — "
                    "no independent weight",
        }

    provider = ResourceEvidenceProvider(
        hunspell_forms=hunspell_forms,
        freq_isv=freq_isv,
        freq_isvx=freq_isvx,
        slovnik_index=slovnik_index,
        provenance=provenance,
    )
    return provider if provider.available else None
